create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  guest_name text not null,
  message text not null,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.wishes enable row level security;

do $$ begin
  create policy "Public can submit guestbook wishes" on public.wishes
  for insert to anon, authenticated with check (length(trim(guest_name)) > 0 and length(trim(message)) > 0);
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "Public can read approved wishes" on public.wishes
  for select to anon, authenticated using (approved = true);
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "Admins can read all wishes" on public.wishes
  for select to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy "Admins can approve wishes" on public.wishes
  for update to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
exception when duplicate_object then null; end $$;
